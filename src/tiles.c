void maze_draw(u8 level)
{
    maze_draw_zone(level, 0);
}

void maze_draw_zone(u8 level, u8 zone)
{
    u8 row;
    u8 col;
    for (row = 0; row < MAZE_ROWS; row++) {
        for (col = 0; col < MAZE_COLS; col++) {
            maze_draw_cell_zone(level, zone, col, row);
        }
    }
}
