void tiles_install(void)
{
    InstallTileSetAt(
        (const unsigned short (*)[8])game_tiles,
        56,     /* 7 tiles x 8 words */
        T_WALL);

    InstallTileSetAt(
        (const unsigned short (*)[8])title_tiles,
        1760,   /* 220 tiles x 8 words */
        TITLE_TILE_START);

    palettes_install();

    SetBackgroundColour(RGB(0, 0, 0));
}

void maze_draw(u8 level)
{
    u8 row;
    u8 col;
    u8 cell;
    u16 tilenum;

    /* Maze rows 0-8 occupy tile rows 1-9 on SCR_1 (row 0 = HUD layer) */
    for (row = 0; row < 9; row++) {
        for (col = 0; col < 32; col++) {
            cell = maze_map[level][row][col];
            if (cell == 1) {
                tilenum = T_WALL + (P_WALL << 9);
                PutTile(SCR_1_PLANE, P_WALL, col, row + 1, T_WALL);
            } else if (cell == 2) {
                PutTile(SCR_1_PLANE, P_KEY, col, row + 1, T_KEY);
            } else {
                PutTile(SCR_1_PLANE, 0, col, row + 1, 0);
            }
        }
    }
}

